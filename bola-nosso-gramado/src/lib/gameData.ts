// Dados dos times da Série A do Brasileirão com escalações reais + lendas do futebol brasileiro.
// Uso não-comercial / fan game.

export type Position = "GOL" | "ZAG" | "MEI" | "ATA";

// Papel refinado do jogador (posição específica). Ver src/lib/roles.ts.
export type PlayerRole =
  | "GOL" | "LAT_D" | "LAT_E" | "ZAG"
  | "VOL" | "MEI" | "MEC"
  | "PON_D" | "PON_E" | "CA";

export interface Player {
  name: string;
  position: Position;
  overall: number; // 50-99
  club?: string; // clube original (para mostrar no draft)
  legend?: boolean;
  roles?: PlayerRole[]; // 1-2 posições refinadas; se ausente, derivadas por heurística
  // Função efetiva na escalação atual (ex.: Ronaldinho escalado como PON_D).
  // Quando presente, prevalece sobre `roles` no cálculo de artilharia — o
  // jogador atua na função em que o técnico o escalou, não na "melhor" dele.
  activeRole?: PlayerRole;
  // Jogador reserva do clube: só aparece no pool do draft se o técnico
  // desbloqueou o nó correspondente da árvore "Olheiro".
  //   1 = revelado com "Olheiro Regional" (Tier 1) → pool 12
  //   2 = revelado com "Scouting Global" (Tier 2) → pool 13
  reserve?: 1 | 2;
}

export interface Team {
  id: string;
  name: string;
  short: string;
  color: string;
  color2: string;
  players: Player[];
}

