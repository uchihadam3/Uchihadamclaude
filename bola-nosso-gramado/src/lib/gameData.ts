// Garante cobertura mínima de posições refinadas em cada time. Se faltar
// (ou tiver só 1) jogador em algum role — LAT_D, VOL, PON_E etc. —
// aproveita um jogador existente da mesma posição broad e adiciona esse
// role como secundário. Assim, todo time real sempre tem opção de
// escolha em qualquer posição do campo durante o draft, sem inventar
// jogadores falsos.
(function ensureRoleCoverage() {
  const REQUIRED: Record<Position, PlayerRole[]> = {
    GOL: ["GOL"],
    ZAG: ["LAT_D", "LAT_E", "ZAG"],
    MEI: ["VOL", "MEI", "MEC"],
    ATA: ["PON_D", "PON_E", "CA"],
  };
  const MIN_PER_ROLE = 2;
  for (const team of TEAMS) {
    for (const pos of Object.keys(REQUIRED) as Position[]) {
      for (const role of REQUIRED[pos]) {
        const count = () => team.players.filter((p) => (p.roles ?? []).includes(role)).length;
        let guard = 0;
        while (count() < MIN_PER_ROLE && guard++ < 20) {
          const cand = team.players
            .filter((p) => p.position === pos && !(p.roles ?? []).includes(role))
            .sort((a, b) => (a.roles?.length ?? 0) - (b.roles?.length ?? 0) || b.overall - a.overall);
          if (!cand.length) break;
          const p = cand[0];
          p.roles = [...(p.roles ?? []), role];
        }
      }
    }
  }
})();

// Ajuste natural dos overalls dos times internacionais:
//  - Mundial: -2 pontos (times de elite europeus/sauditas continuam
//    fortíssimos; alinha com a percepção de que times brasileiros são
//    competitivos, não inferiores por 5+ pontos).
//  - Libertadores/Sul-Americana: boost por faixa para deixar mais
//    equilibrado com o Brasileirão. Fortes +1, médios +2, fracos +3.
// Aplicado tanto no `overall` do time quanto no overall de cada jogador,
// direto no pool — `freshenIntlSquad` rehidrata elencos daqui, então
// saves antigos passam a ver os valores atualizados.
(function tuneIntlTeams() {
  const FLOOR = 60;
  const CAP = 99;

  // Mundial: -2
  for (const t of MUNDIAL_RIVALS) {
    t.overall = Math.max(FLOOR, t.overall - 2);
    if (t.players) {
      for (const p of t.players) p.overall = Math.max(FLOOR, p.overall - 2);
    }
  }

  // Boost por faixa para Liberta/Sula.
  const boostFor = (ovr: number) => (ovr >= 80 ? 1 : ovr >= 75 ? 2 : 3);
  for (const pool of [LIBERTADORES_RIVALS, SULAMERICANA_RIVALS]) {
    for (const t of pool) {
      const bTeam = boostFor(t.overall);
      t.overall = Math.min(CAP, t.overall + bTeam);
      if (t.players) {
        for (const p of t.players) {
          p.overall = Math.min(CAP, p.overall + boostFor(p.overall));
        }
      }
    }
  }
})();

// Rehidrata um elenco de time internacional a partir do pool atual (útil
// pra saves antigos que persistiram snapshots com OVR desatualizados).
// Se não achar o time nos pools, devolve o próprio input.
export function freshenIntlSquad(teamName: string, fallback: Player[] | undefined): Player[] {
  const pools: IntlTeam[][] = [MUNDIAL_RIVALS, LIBERTADORES_RIVALS, SULAMERICANA_RIVALS];
  for (const pool of pools) {
    const hit = pool.find((t) => t.name === teamName);
    if (hit) return (hit.players ?? []) as Player[];
  }
  const t = TEAMS.find((x) => x.name === teamName);
  if (t) return t.players ?? [];
  return fallback ?? [];
}


// Nivelamento: garante que nenhum time fique fraco demais.
// Se o overall dos 11 melhores de um time for menor que MIN_TOP11,
// soma um delta em todos os jogadores daquele time (cap 99).
(function levelTeams() {
  // Sem piso rígido: times de Série B/C podem (e devem) ser mais fracos que
  // os grandes. Só evitamos casos absurdos (< 68) dando um empurrão leve, e
  // apertamos a faixa média pra que o Brasileirão não seja sempre passeio
  // pros grandes — mas sem transformar todo mundo no mesmo time.
  const top11Avg = (t: (typeof TEAMS)[number]) => {
    const top = [...t.players].sort((a, b) => b.overall - a.overall).slice(0, 11);
    return top.reduce((s, p) => s + p.overall, 0) / Math.max(1, top.length);
  };
  for (const t of TEAMS) {
    if (!t.players.length) continue;
    const avg = top11Avg(t);
    let bump = 0;
    // Piso muito baixo: só quem está em nível pré-Série C ganha +1/+2.
    if (avg < 66) bump = 2;
    else if (avg < 70) bump = 1;
    // Faixa média competitiva do Brasileirão (70-78) ganha +1 sutil pra
    // que times de 70-73 não fiquem em desvantagem estrutural depois do
    // buff da faixa 74-78.
    else if (avg >= 70 && avg < 78) bump = 1;
    if (bump > 0) {
      for (const p of t.players) p.overall = Math.min(99, p.overall + bump);
    }
  }
})();

// Buff geral do Brasileirão: +1 OVR em todos os times exceto Palmeiras e
// Flamengo, que recebem -1 pra manter os dois gigantes acima mas mais
// próximos do restante da liga.
(function buffBrasileiraoExceptTopTwo() {
  const TOP_TWO = new Set(["palmeiras", "flamengo"]);
  for (const t of TEAMS) {
    const delta = TOP_TWO.has(t.id) ? -2 : 0;
    for (const p of t.players) p.overall = Math.max(40, Math.min(99, p.overall + delta));
  }
})();

// ─── Micro-offset determinístico (casa decimal) ──────────────────────
// Cada jogador ganha um deslocamento pequeno (±0,49) baseado no hash do
// nome+clube. Isso faz com que dois jogadores exibidos como "OVR 82"
// tenham valores levemente diferentes de verdade (ex.: 82,3 vs 81,8),
// visíveis no draft com "Bom com números" e usados diretamente pelo
// motor de partida (que sempre trabalha com decimais). A média por
// elenco fica ~0 → não altera dificuldade global.
(function applyMicroOffsets() {
  const hash = (s: string) => {
    let h = 0x811c9dc5;
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 0x01000193);
    }
    return h >>> 0;
  };
  const microFor = (name: string, club: string) => {
    const r = (hash(`${name}|${club}`) % 1000) / 1000; // 0..0.999
    return Math.round((r * 0.98 - 0.49) * 10) / 10; // ±0.4 em passos de 0.1
  };
  for (const t of TEAMS) {
    for (const p of t.players) {
      p.overall = Math.max(40, Math.min(99.9, p.overall + microFor(p.name, t.short)));
    }
  }
  for (const p of LEGENDS) {
    p.overall = Math.max(40, Math.min(99.9, p.overall + microFor(p.name, "LENDA")));
  }
})();





