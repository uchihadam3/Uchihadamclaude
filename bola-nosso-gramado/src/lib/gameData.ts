// Buff das lendas: +1 para OVR <= 97, +2 para OVR <= 89 (nacionais e internacionais). Cap 99.
(function buffLegends() {
  const bump = (list: Player[]) => {
    for (const p of list) {
      if (p.overall <= 89) p.overall = Math.min(99, p.overall + 2);
      else if (p.overall <= 97) p.overall = Math.min(99, p.overall + 1);
    }
  };
  bump(LEGENDS);
  bump(INTERNATIONAL_LEGENDS);
})();



// Pool completo: todos os jogadores da Série A + lendas, com clube marcado
export function buildPlayerPool(): Player[] {
  const pool: Player[] = [];
  for (const t of TEAMS) {
    for (const p of t.players) {
      pool.push({ ...p, club: t.name });
    }
  }
  for (const l of LEGENDS) pool.push({ ...l });
  return pool;
}

